#!/usr/bin/env python3
"""Regenerate rtl/pkg/imem_boot_pkg.vhd from sw/hex/uart_hello.hex."""
from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HEX = ROOT / "sw" / "hex" / "uart_hello.hex"
OUT = ROOT / "rtl" / "pkg" / "imem_boot_pkg.vhd"


def main() -> None:
    words: list[str] = []
    for line in HEX.read_text().splitlines():
        line = line.strip()
        if len(line) >= 8 and all(c in "0123456789abcdefABCDEF" for c in line[:8]):
            words.append(line[:8].lower())
    if not words:
        raise SystemExit(f"no words in {HEX}")
    while len(words) < 32:
        words.append("00000013")

    body = "\n".join(
        f'    {i} => x"{w}"' + ("," if i + 1 < len(words) else "")
        for i, w in enumerate(words)
    )
    OUT.write_text(
        "\n".join(
            [
                "library ieee;",
                "use ieee.std_logic_1164.all;",
                "use work.rv32_pkg.all;",
                "",
                f"-- Auto-generated by sw/scripts/gen_imem_boot_pkg.py from {HEX.relative_to(ROOT)}",
                "-- Embedded so Vivado synth does not depend on VHDL textio file_open.",
                "package imem_boot_pkg is",
                f"  constant IMEM_BOOT_LEN : natural := {len(words)};",
                "  type imem_boot_t is array (0 to IMEM_BOOT_LEN - 1) of word_t;",
                "  constant IMEM_BOOT_IMAGE : imem_boot_t := (",
                body,
                "  );",
                "end package;",
                "",
            ]
        )
    )
    print(f"wrote {OUT.relative_to(ROOT)} ({len(words)} words)")


if __name__ == "__main__":
    main()
